"""
Generate administrative quiz questions for Nepal.

Administrative levels:
    ADM1: Provinces (7)
    ADM2: Districts (77)
    ADM3: Local levels (753)

Input:
    public/data/countries/nepal/geojson/nepal_adm1.geojson
    public/data/countries/nepal/geojson/nepal_adm2.geojson
    public/data/countries/nepal/geojson/nepal_adm3.geojson

Output:
    src/quiz/quizzes/countries/asia/nepal/data/admin.ts

Usage:
    python scripts/countries/asia/nepal/generate/admin-quiz-data.py
"""

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[5]

INPUT_DIR = ROOT / "public/data/countries/nepal/geojson"
OUTPUT_DIR = ROOT / "src/quiz/quizzes/countries/asia/nepal/data"
OUTPUT_FILE = OUTPUT_DIR / "admin.ts"

DATASETS = [
    ("nepal_adm1.geojson", "nepalProvinceQuestions", 7),
    ("nepal_adm2.geojson", "nepalDistrictQuestions", 77),
    ("nepal_adm3.geojson", "nepalLocalLevelQuestions", 753),
]


def load_questions(filename, expected_count):
    path = INPUT_DIR / filename

    with path.open(encoding="utf-8") as file:
        features = json.load(file)["features"]

    questions = []

    for feature in features:
        props = feature["properties"]

        questions.append({
            "answer": str(props["admin_id"]),
            "display": props["name"],
            "nativeDisplay": props["nativeName"],
        })

    questions.sort(
        key=lambda question: (
            question["display"].casefold(),
            question["answer"],
        )
    )

    if len(questions) != expected_count:
        raise ValueError(
            f"{filename}: expected {expected_count} questions, "
            f"found {len(questions)}."
        )

    answers = [question["answer"] for question in questions]

    if len(answers) != len(set(answers)):
        raise ValueError(f"{filename}: duplicate answer IDs.")

    return questions


def format_questions(export_name, questions):
    lines = [
        f"export const {export_name}: FeatureQuizQuestion[] = ["
    ]

    for question in questions:
        answer = json.dumps(
            question["answer"],
            ensure_ascii=False,
        )
        display = json.dumps(
            question["display"],
            ensure_ascii=False,
        )
        native_display = json.dumps(
            question["nativeDisplay"],
            ensure_ascii=False,
        )

        lines.append(
            f"  {{ answer: {answer}, "
            f"display: {display}, "
            f"nativeDisplay: {native_display} }},"
        )

    lines.append("];")

    return "\n".join(lines)


def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    sections = [
        "// Auto-generated by admin-quiz-data.py.",
        "// Do not edit manually.",
        "",
        'import type { FeatureQuizQuestion } from "@/quiz/types";',
    ]

    total_questions = 0

    for filename, export_name, expected_count in DATASETS:
        questions = load_questions(filename, expected_count)

        sections.append("")
        sections.append(format_questions(export_name, questions))

        total_questions += len(questions)

        print(f"{export_name}: {len(questions)} questions")

    OUTPUT_FILE.write_text(
        "\n".join(sections) + "\n",
        encoding="utf-8",
    )

    print(f"\nTotal questions: {total_questions}")
    print(f"Written: {OUTPUT_FILE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()