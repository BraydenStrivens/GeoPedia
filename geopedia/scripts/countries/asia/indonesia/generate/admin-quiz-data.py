"""
Generate Indonesia geographic-region and administrative quiz data for GeoPedia.

Purpose
-------
This script reads GeoPedia's canonical intermediate Indonesia GeoJSON files and
generates TypeScript question arrays for the five Indonesia boundary quizzes:

    Regions
    Provinces
    Regencies
    Sub-Districts
    Villages

The geographic regions are generated separately by:

    scripts/countries/indonesia/process/regions.py

The four administrative datasets are generated by:

    scripts/countries/indonesia/process/admin.py

Inputs
------
    data/intermediate/countries/indonesia/
        regions.geojson
        provinces.geojson
        regencies.geojson
        sub-districts.geojson
        villages.geojson

Outputs
-------
    src/quiz/quizzes/countries/asia/indonesia/data/
        admin.ts
        sub-districts.ts
        villages.ts

Output organization
-------------------
admin.ts:
    INDONESIA_REGION_QUESTIONS
    INDONESIA_PROVINCE_QUESTIONS
    INDONESIA_REGENCY_QUESTIONS

sub-districts.ts:
    INDONESIA_SUB_DISTRICT_QUESTIONS

villages.ts:
    INDONESIA_VILLAGE_QUESTIONS

Question answers
----------------
Every question uses the stable canonical ID stored in its GeoJSON as its answer:

    region_id
    province_id
    regency_id
    sub_district_id
    village_id

The human-readable geographic or administrative name is stored as display.

Region labels
-------------
The Regions quiz uses the Indonesian/native region name first and appends the
English name when it differs:

    Sumatera (Sumatra)
    Jawa (Java)
    Nusa Tenggara (Lesser Sunda Islands)
    Kalimantan
    Sulawesi
    Maluku (Maluku Islands)
    Papua (Western New Guinea)

The English name comes from region_english in regions.geojson.

region_english is intentionally needed only for the standalone Regions quiz.
It is not duplicated across the four lower administrative GeoJSON datasets.

Duplicate-name disambiguation
-----------------------------
Names that are globally unique are emitted normally:

    { answer: "ID...", display: "Name" }

When a name occurs more than once in an administrative dataset, its immediate
parent is appended to display:

    Regency:
        Name (Province)

    Sub-District:
        Name (Regency)

    Village:
        Name (Sub-District)

Only names that are actually duplicated receive the parent suffix.

Duplicate displays are explicitly allowed to remain for Sub-Districts and
Villages after immediate-parent disambiguation. The script does not append
additional hierarchy levels merely to force every display to be globally
unique.

Stable canonical IDs remain the actual unique quiz answers.

Requirements
------------
    pip install ijson

Run from the GeoPedia project root:

    python scripts/countries/indonesia/generate/admin-quiz-data.py

The generated TypeScript files should not be edited manually. Regenerate them
from the canonical intermediate GeoJSON whenever the source data changes.
"""

