"""
Generate Thailand's administrative quiz question arrays for GeoPedia.

Reads processed province, district, and subdistrict GeoJSON files and
generates TypeScript FeatureQuizQuestion arrays with English answers,
Thai native labels, and parent administrative grouping.

Inputs:
    public/data/countries/thailand/geojson/
        provinces.geojson
        districts.geojson
        subdistricts.geojson

Output:
    src/quiz/quizzes/countries/asia/thailand/data/admin.ts

Usage:
    python scripts/countries/asia/thailand/generate/admin-quiz-data.py

This file is generated from processed GeoJSON. Regenerate it after
updating Thailand's administrative boundary data.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


PROJECT_ROOT = Path(__file__).resolve().parents[5]

GEOJSON_DIR = (
    PROJECT_ROOT
    / "public/data/countries/thailand/geojson"
)

OUTPUT_PATH = (
    PROJECT_ROOT
    / "src/quiz/quizzes/countries/asia/thailand/data/admin.ts"
)


def load_features(filename: str) -> list[dict[str, Any]]:
    """Load features from a processed GeoJSON file."""

    path = GEOJSON_DIR / filename

    with path.open("r", encoding="utf-8") as file:
        data = json.load(file)

    return data["features"]


def ts_string(value: str) -> str:
    """Encode a string safely for TypeScript."""

    return json.dumps(value, ensure_ascii=False)


def write_question(
    lines: list[str],
    question: dict[str, Any],
) -> None:
    """Append one formatted TypeScript question."""

    lines.append("  {")

    for key, value in question.items():
        lines.append(f"    {key}: {ts_string(value)},")

    lines.append("  },")


def build_province_questions(
    features: list[dict[str, Any]],
) -> list[dict[str, str]]:
    questions = []

    for feature in features:
        properties = feature["properties"]

        questions.append({
            "answer": properties["province_id"],
            "display": properties["province"],
            "nativeDisplay": properties["province_native"],
        })

    return sorted(questions, key=lambda question: question["answer"])


def build_district_questions(
    features: list[dict[str, Any]],
) -> list[dict[str, str]]:
    questions = []

    for feature in features:
        properties = feature["properties"]

        questions.append({
            "answer": properties["district_id"],
            "display": properties["district"],
            "nativeDisplay": properties["district_native"],
        })

    return sorted(questions, key=lambda question: question["answer"])


def build_subdistrict_questions(
    features: list[dict[str, Any]],
) -> list[dict[str, str]]:
    questions = []

    for feature in features:
        properties = feature["properties"]

        questions.append({
            "answer": properties["subdistrict_id"],
            "display": properties["subdistrict"],
            "nativeDisplay": properties["subdistrict_native"],
        })

    return sorted(questions, key=lambda question: question["answer"])


def write_array(
    lines: list[str],
    name: str,
    questions: list[dict[str, str]],
) -> None:
    lines.append(
        f"export const {name}: FeatureQuizQuestion[] = ["
    )

    for question in questions:
        write_question(lines, question)

    lines.append("];")
    lines.append("")


def main() -> None:
    provinces = load_features("provinces.geojson")
    districts = load_features("districts.geojson")
    subdistricts = load_features("subdistricts.geojson")

    province_questions = build_province_questions(provinces)
    district_questions = build_district_questions(districts)

    district_names = {
        feature["properties"]["district_id"]:
        feature["properties"]["district"]
        for feature in districts
    }

    subdistrict_questions = build_subdistrict_questions(subdistricts)

    lines = [
        "/**",
        " * Thailand administrative quiz questions.",
        " *",
        " * Generated by:",
        " * scripts/countries/asia/thailand/generate/admin-quiz-data.py",
        " *",
        " * Do not edit manually. Regenerate after processing",
        " * Thailand's administrative GeoJSON datasets.",
        " */",
        "",
        'import type { FeatureQuizQuestion } from "@/types/quiz";',
        "",
    ]

    write_array(
        lines,
        "THAILAND_PROVINCE_QUESTIONS",
        province_questions,
    )

    write_array(
        lines,
        "THAILAND_DISTRICT_QUESTIONS",
        district_questions,
    )

    write_array(
        lines,
        "THAILAND_SUBDISTRICT_QUESTIONS",
        subdistrict_questions,
    )

    OUTPUT_PATH.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    OUTPUT_PATH.write_text(
        "\n".join(lines),
        encoding="utf-8",
    )

    print("Thailand administrative quiz data generated")
    print(f"  Provinces:    {len(province_questions):,}")
    print(f"  Districts:    {len(district_questions):,}")
    print(f"  Subdistricts: {len(subdistrict_questions):,}")
    print(f"  Output: {OUTPUT_PATH.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()